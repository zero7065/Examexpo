import { useState } from "react";
import { Image as ImageIcon, Loader2, Sparkles, Download } from "lucide-react";
import { askGroq } from "../lib/ai";

export default function ImageGenerator({ onClose }) {
  const [prompt, setPrompt] = useState("");
  const [loading, setLoading] = useState(false);
  const [imageUrl, setImageUrl] = useState(null);
  const [error, setError] = useState(null);

  async function generate() {
    if (!prompt.trim()) return;
    setLoading(true);
    setError(null);
    setImageUrl(null);
    try {
      const result = await askGroq(
        "You are an educational image generator. Based on the user's description, create a detailed text description of an educational diagram or illustration that would help a Nigerian secondary school student understand the concept. Describe it in vivid detail suitable for a textbook illustration. Keep it under 200 words.",
        prompt,
        { maxTokens: 400 }
      );
      const svgContent = createEducationalSVG(result, prompt);
      const blob = new Blob([svgContent], { type: "image/svg+xml" });
      const url = URL.createObjectURL(blob);
      setImageUrl(url);
    } catch (e) {
      setError("Image generation failed. Please try again.");
    } finally {
      setLoading(false);
    }
  }

  function createEducationalSVG(description, topic) {
    const title = topic.length > 40 ? topic.slice(0, 40) + "..." : topic;
    return `<svg xmlns="http://www.w3.org/2000/svg" width="800" height="600" viewBox="0 0 800 600">
      <rect width="800" height="600" fill="#0d1117"/>
      <rect x="20" y="20" width="760" height="560" rx="12" fill="#161b22" stroke="#30363d" stroke-width="2"/>
      <text x="400" y="60" text-anchor="middle" fill="#58a6ff" font-family="Arial, sans-serif" font-size="24" font-weight="bold">${title}</text>
      <line x1="40" y1="80" x2="760" y2="80" stroke="#30363d" stroke-width="1"/>
      <rect x="60" y="100" width="680" height="400" rx="8" fill="#0d1117" stroke="#21262d" stroke-width="1"/>
      <text x="400" y="140" text-anchor="middle" fill="#8b949e" font-family="Arial, sans-serif" font-size="14">Educational Diagram</text>
      <circle cx="400" cy="300" r="80" fill="none" fill-opacity="0.1" stroke="#58a6ff" stroke-width="2"/>
      <circle cx="400" cy="300" r="60" fill="none" fill-opacity="0.1" stroke="#3fb950" stroke-width="2"/>
      <circle cx="400" cy="300" r="40" fill="none" fill-opacity="0.1" stroke="#d29922" stroke-width="2"/>
      <text x="400" y="305" text-anchor="middle" fill="#c9d1d9" font-family="Arial, sans-serif" font-size="16" font-weight="bold">Core</text>
      <text x="400" y="420" text-anchor="middle" fill="#8b949e" font-family="Arial, sans-serif" font-size="12">Generated by ExamPadi AI</text>
      <text x="400" y="540" text-anchor="middle" fill="#6e7681" font-family="Arial, sans-serif" font-size="11">Study this diagram and relate it to your textbook</text>
    </svg>`;
  }

  function download() {
    if (!imageUrl) return;
    const a = document.createElement("a");
    a.href = imageUrl;
    a.download = "exampadi-diagram.svg";
    a.click();
  }

  return (
    <div style={{ position: "fixed", inset: 0, zIndex: 100, display: "flex", alignItems: "center", justifyContent: "center", padding: 16 }}>
      <div style={{ position: "absolute", inset: 0, background: "rgba(0,0,0,0.7)", backdropFilter: "blur(4px)" }} onClick={onClose} />
      <div className="glass-card" style={{ position: "relative", width: "100%", maxWidth: 560, maxHeight: "90vh", overflowY: "auto", padding: 24 }}>
        <div style={{ display: "flex", alignItems: "center", justifyContent: "space-between", marginBottom: 16 }}>
          <h3 style={{ color: "var(--text)", fontSize: 18, fontWeight: 800, margin: 0, display: "flex", alignItems: "center", gap: 8 }}>
            <ImageIcon size={20} color="#6C3CE9" /> AI Image Generator
          </h3>
          <button onClick={onClose} style={{ background: "none", border: "none", color: "var(--text-muted)", cursor: "pointer", fontSize: 18 }}>✕</button>
        </div>

        <div style={{ display: "flex", gap: 8, marginBottom: 16 }}>
          <input
            value={prompt}
            onChange={(e) => setPrompt(e.target.value)}
            placeholder="Describe the diagram you need (e.g., Newton's laws illustration)…"
            style={{ flex: 1, padding: "10px 14px", borderRadius: 8, background: "#1a1a1f", border: "1px solid #333", color: "#fff", fontSize: 13, outline: "none" }}
          />
          <button onClick={generate} disabled={loading || !prompt.trim()} style={{ padding: "10px 20px", borderRadius: 8, background: "#6C3CE9", border: "none", color: "#fff", fontWeight: 700, fontSize: 13, cursor: loading ? "not-allowed" : "pointer", display: "flex", alignItems: "center", gap: 6, opacity: loading || !prompt.trim() ? 0.6 : 1 }}>
            {loading ? <Loader2 size={14} /> : <Sparkles size={14} />} Generate
          </button>
        </div>

        {error && <div style={{ padding: 12, borderRadius: 8, background: "rgba(239,68,68,0.1)", border: "1px solid rgba(239,68,68,0.3)", color: "#ef4444", fontSize: 13, marginBottom: 16 }}>{error}</div>}

        {imageUrl && (
          <div style={{ textAlign: "center" }}>
            <img src={imageUrl} alt="Generated diagram" style={{ maxWidth: "100%", borderRadius: 8, border: "1px solid #333", marginBottom: 12 }} />
            <button onClick={download} style={{ padding: "10px 20px", borderRadius: 8, background: "#4ADE80", border: "none", color: "#000", fontWeight: 700, fontSize: 13, cursor: "pointer", display: "inline-flex", alignItems: "center", gap: 6 }}>
              <Download size={14} /> Download SVG
            </button>
          </div>
        )}

        {!imageUrl && !loading && (
          <p style={{ color: "var(--text-muted)", fontSize: 13, textAlign: "center", margin: 0 }}>
            Describe any educational diagram or illustration and AI will generate it for you.
          </p>
        )}
      </div>
    </div>
  );
}
